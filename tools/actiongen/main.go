// Command actiongen writes the subdirectory GitHub Actions (<name>/action.yml)
// and the argv table the shared runner reads (action-lib/commands.sh), all from
// the spec table in spec.go. The files are generated, not hand-written, so every
// action has the same inputs and the same injection-safe shape. The docs site
// builds its pages from these action.yml files at the Latest release tag;
// TestGeneratedFilesAreCurrent fails when they drift.
//
//	go generate ./tools/actiongen
package main

//go:generate go run . -root ../..

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "report stale files and exit 1 instead of writing")
	flag.Parse()
	files := generate()
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	stale := 0
	for _, n := range names {
		p := filepath.Join(*root, n)
		old, _ := os.ReadFile(p)
		if bytes.Equal(old, files[n]) {
			continue
		}
		if *check {
			fmt.Println("stale:", n)
			stale++
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if err := os.WriteFile(p, files[n], 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Println("wrote", n)
	}
	if stale > 0 {
		os.Exit(1)
	}
}

const header = "# Generated by tools/actiongen from tools/actiongen/spec.go. Do not edit;\n# change the spec and run `go generate ./tools/actiongen`.\n"

// generate returns every generated file by its path from the repository root.
func generate() map[string][]byte {
	out := map[string][]byte{}
	for _, a := range actions {
		out[dirOf(a)+"/action.yml"] = []byte(actionYAML(a))
	}
	out["action-lib/commands.sh"] = []byte(commandsSh())
	out[".github/workflows/actions-e2e.yml"] = []byte(e2eWorkflow())
	return out
}

// common is an input every action except setup has.
type common struct {
	input
	when func(action) bool
}

func always(action) bool { return true }

var commonInputs = []common{
	{input{Name: "version", Desc: "Release of the Vulnetix CLI to install. Empty installs the release this action ref was cut from, which is what a lock file or a SHA pin expects. An exact tag (v4.0.0), a major channel (v4) or latest float instead"}, always},
	{input{Name: "binary-path", Desc: "Path to an already-built vulnetix binary to use instead of downloading a release"}, always},
	{input{Name: "verify-provenance", Desc: "Verify the downloaded CLI against the signed SLSA provenance of its release with cosign, which this action installs: true or false. Every v4 release is signed; set false to install a v3 release that has no provenance.sigstore.json. The SHA-256 checksum is checked either way", Default: "true"}, always},
	{input{Name: "org-id", Desc: "Vulnetix organization ID (UUID), used with api-key. Optional: without credentials the CLI runs in community mode"}, notSetup},
	{input{Name: "api-key", Desc: "Vulnetix API key. Passed to the CLI as VULNETIX_API_KEY, never on the command line"}, notSetup},
	{input{Name: "api-token", Desc: "Vulnetix API token; the server resolves the organization. Passed as VULNETIX_API_TOKEN"}, notSetup},
	{input{Name: "path", Desc: "Directory to scan", Default: "."}, func(a action) bool { return a.Path || a.Script == "publish" }},
	{input{Name: "args", Desc: "Extra arguments for the command, separated by spaces or newlines (no shell quoting is applied)"}, generic},
	{input{Name: "extra-args", Desc: "Extra arguments, one per line, so a value may contain spaces"}, passesArgs},
	{input{Name: "artifact-name", Desc: "Upload every file the command wrote as a workflow artifact with this name"}, notSetup},
	{input{Name: "fail-on-findings", Desc: "Fail the step when the command exits non-zero (findings over a gate, a breach, an error): true or false. The artifact, attestation and publish steps run either way", Default: "true"}, notSetup},
	{input{Name: "github-code-scanning", Desc: "Upload SARIF to GitHub code scanning (needs security-events: write): true or false", Default: "false"}, func(a action) bool { return a.CodeScanning }},
	{input{Name: "dependency-graph", Desc: "Submit the SBOM to the GitHub dependency graph (needs contents: write): true or false", Default: "false"}, func(a action) bool { return a.DependencyGraph }},
	{input{Name: "github-token", Desc: "Token for GitHub publishing, release assets and pull request comments", Default: "${{ github.token }}"}, notSetup},
	{input{Name: "attest", Desc: "Attest the written files with GitHub artifact attestations (needs id-token: write and attestations: write): true or false", Default: "false"}, notSetup},
	{input{Name: "release-tag", Desc: "Attach every file the command wrote to the GitHub release with this tag (needs contents: write)"}, notSetup},
}

// dirOf is where an action lives.
func dirOf(a action) string {
	if a.Dir != "" {
		return a.Dir
	}
	return a.Name
}

// libPath is the action-lib directory seen from the action's own directory.
func libPath(a action) string {
	return "$GITHUB_ACTION_PATH/" + strings.Repeat("../", strings.Count(dirOf(a), "/")+1) + "action-lib"
}

func notSetup(a action) bool { return !a.Setup }
func generic(a action) bool  { return !a.Setup && (a.Script == "" || a.Script == "fix") }
func passesArgs(a action) bool {
	return generic(a) || a.Script == "config"
}

func inputsOf(a action) []input {
	var in []input
	for _, c := range commonInputs {
		if c.when(a) {
			in = append(in, c.input)
		}
	}
	return append(in, a.Inputs...)
}

func envName(input string) string {
	return "VX_IN_" + strings.ToUpper(strings.ReplaceAll(input, "-", "_"))
}

func q(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func outputsOf(a action) [][2]string {
	if a.Setup {
		return [][2]string{{"version", "The installed CLI version"}}
	}
	return [][2]string{
		{"files", "Every file the command wrote, one per line"},
		{"sarif", "The SARIF files it wrote, one per line"},
		{"sbom", "The CycloneDX SBOM it wrote, if any"},
		{"manifest", "The artifact manifest (JSON Lines) listing what it wrote"},
		{"exit-code", "The command's exit code"},
		{"result", "success or failure"},
		{"summary", "One line saying what ran and how it ended"},
	}
}

func actionYAML(a action) string {
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "name: %s\n", q("Vulnetix "+a.Title))
	fmt.Fprintf(&b, "description: %s\n", q(a.Desc))
	b.WriteString("author: 'Vulnetix'\nbranding:\n  icon: 'shield'\n  color: 'red'\n\ninputs:\n")
	for _, in := range inputsOf(a) {
		fmt.Fprintf(&b, "  %s:\n    description: %s\n    required: false\n", in.Name, q(in.Desc))
		if in.Default != "" {
			if strings.HasPrefix(in.Default, "${{") {
				fmt.Fprintf(&b, "    default: %s\n", in.Default)
			} else {
				fmt.Fprintf(&b, "    default: %s\n", q(in.Default))
			}
		}
	}
	b.WriteString("\noutputs:\n")
	for _, o := range outputsOf(a) {
		step := "run"
		if a.Setup {
			step = "install"
		}
		fmt.Fprintf(&b, "  %s:\n    description: %s\n    value: ${{ steps.%s.outputs.%s }}\n", o[0], q(o[1]), step, o[0])
	}
	b.WriteString("\nruns:\n  using: 'composite'\n  steps:\n")
	fmt.Fprintf(&b, "    - name: Install cosign\n      if: inputs.verify-provenance == 'true' && inputs.binary-path == ''\n      uses: %s\n\n", cosignInstall)
	b.WriteString(`    - name: Install the Vulnetix CLI
      id: install
      shell: bash
      env:
        VX_VERSION: ${{ inputs.version }}
        VX_BINARY_PATH: ${{ inputs.binary-path }}
        VX_VERIFY_PROVENANCE: ${{ inputs.verify-provenance }}
      run: bash "` + libPath(a) + `/install.sh"
`)
	if a.Setup {
		return b.String()
	}

	// Every input reaches the scripts as an environment variable. Nothing
	// below interpolates an expression into a script.
	fmt.Fprintf(&b, `
    - name: Run vulnetix %s
      id: run
      shell: bash
      env:
        VX_ACTION: %s
        VULNETIX_ORG_ID: ${{ inputs.org-id }}
        VULNETIX_API_KEY: ${{ inputs.api-key }}
        VULNETIX_API_TOKEN: ${{ inputs.api-token }}
        GITHUB_TOKEN: ${{ inputs.github-token }}
`, strings.Join(displayCommand(a), " "), a.Name)
	if a.Path || a.Script == "publish" {
		b.WriteString("        VX_PATH: ${{ inputs.path }}\n")
	}
	if generic(a) {
		b.WriteString("        VX_ARGS: ${{ inputs.args }}\n")
	}
	if passesArgs(a) {
		b.WriteString("        VX_EXTRA_ARGS: ${{ inputs.extra-args }}\n")
	}
	if a.Scan {
		if a.CodeScanning {
			b.WriteString("        VX_CODE_SCANNING: ${{ inputs.github-code-scanning }}\n")
		}
		if a.DependencyGraph {
			b.WriteString("        VX_DEPENDENCY_GRAPH: ${{ inputs.dependency-graph }}\n")
		}
	}
	if a.Script == "publish" {
		b.WriteString("        VX_CODE_SCANNING: ${{ inputs.github-code-scanning }}\n        VX_DEPENDENCY_GRAPH: ${{ inputs.dependency-graph }}\n")
	}
	if a.Script == "config" {
		b.WriteString("        VX_EVENT_NAME: ${{ github.event_name }}\n")
	}
	for _, in := range a.Inputs {
		fmt.Fprintf(&b, "        %s: ${{ inputs.%s }}\n", envName(in.Name), in.Name)
	}
	fmt.Fprintf(&b, "      run: bash \"%s/run.sh\"\n", libPath(a))

	if !a.Scan && a.Script != "publish" && (a.CodeScanning || a.DependencyGraph) {
		var cond []string
		b.WriteString("\n    - name: Publish to GitHub\n")
		if a.CodeScanning {
			cond = append(cond, "inputs.github-code-scanning == 'true'")
		}
		if a.DependencyGraph {
			cond = append(cond, "inputs.dependency-graph == 'true'")
		}
		fmt.Fprintf(&b, "      if: ${{ !cancelled() && (%s) }}\n", strings.Join(cond, " || "))
		b.WriteString("      shell: bash\n      env:\n        GITHUB_TOKEN: ${{ inputs.github-token }}\n        VX_MANIFEST: ${{ steps.run.outputs.manifest }}\n")
		if a.Path {
			b.WriteString("        VX_PATH: ${{ inputs.path }}\n")
		}
		if a.CodeScanning {
			b.WriteString("        VX_CODE_SCANNING: ${{ inputs.github-code-scanning }}\n")
		}
		if a.DependencyGraph {
			b.WriteString("        VX_DEPENDENCY_GRAPH: ${{ inputs.dependency-graph }}\n")
		}
		fmt.Fprintf(&b, "      run: bash \"%s/publish.sh\"\n", libPath(a))
	}

	fmt.Fprintf(&b, `
    - name: Upload the written files as an artifact
      if: ${{ !cancelled() && inputs.artifact-name != '' && steps.run.outputs.files != '' }}
      uses: %s
      with:
        name: ${{ inputs.artifact-name }}
        path: ${{ steps.run.outputs.files }}
        if-no-files-found: warn
        include-hidden-files: true
`, uploadArtifact)
	if a.SBOM {
		fmt.Fprintf(&b, `
    - name: Attest the SBOM
      if: ${{ !cancelled() && inputs.attest == 'true' && steps.run.outputs.sbom != '' }}
      uses: %s
      with:
        subject-path: ${{ steps.run.outputs.sbom }}
        sbom-path: ${{ steps.run.outputs.sbom }}
`, attestSBOM)
	} else {
		fmt.Fprintf(&b, `
    - name: Attest the written files
      if: ${{ !cancelled() && inputs.attest == 'true' && steps.run.outputs.files != '' }}
      uses: %s
      with:
        subject-path: ${{ steps.run.outputs.files }}
`, attestBuild)
	}
	b.WriteString(strings.ReplaceAll(`
    - name: Attach the written files to the release
      if: ${{ !cancelled() && inputs.release-tag != '' && steps.run.outputs.manifest != '' }}
      shell: bash
      env:
        GITHUB_TOKEN: ${{ inputs.github-token }}
        VX_RELEASE_TAG: ${{ inputs.release-tag }}
        VX_MANIFEST: ${{ steps.run.outputs.manifest }}
      run: bash "LIB/release-assets.sh"

    - name: Finish
      if: ${{ !cancelled() }}
      shell: bash
      env:
        VX_EXIT_CODE: ${{ steps.run.outputs.exit-code }}
        VX_FAIL_ON_FINDINGS: ${{ inputs.fail-on-findings }}
        VX_SUMMARY: ${{ steps.run.outputs.summary }}
      run: bash "LIB/finish.sh"
`, "LIB", libPath(a)))
	return b.String()
}

func displayCommand(a action) []string {
	switch a.Script {
	case "config":
		return []string{"config", strings.TrimPrefix(a.Name, "config-")}
	case "publish":
		return []string{"gha", "publish"}
	}
	return a.Command
}

// commandsSh is the argv table run.sh reads: for each action, the command and
// how each of its inputs becomes arguments.
func commandsSh() string {
	var b strings.Builder
	b.WriteString("#!/usr/bin/env bash\n" + header + `#
# vx_build ACTION fills the array cmd with the argv after "vulnetix" and sets
# vx_scan=true for a scan-family command. Input values come from VX_IN_*
# environment variables and are only ever placed in argv, never evaluated.
# shellcheck disable=SC2034

vx_build() {
  cmd=()
  vx_scan=false
  vx_takes_path=false
  case "$1" in
`)
	for _, a := range actions {
		if !generic(a) {
			continue
		}
		fmt.Fprintf(&b, "    %s)\n      cmd=(%s)\n", a.Name, strings.Join(a.Command, " "))
		if a.Scan {
			b.WriteString("      vx_scan=true\n")
		}
		if a.Path {
			b.WriteString("      vx_takes_path=true\n")
		}
		for _, in := range a.Inputs {
			v := "\"${" + envName(in.Name) + ":-}\""
			switch {
			case in.Flag == "lines":
				fmt.Fprintf(&b, "      vx_lines %s\n", v)
			case strings.HasPrefix(in.Flag, "lines:"):
				fmt.Fprintf(&b, "      vx_flag_lines %s %s\n", strings.TrimPrefix(in.Flag, "lines:"), v)
			case strings.HasPrefix(in.Flag, "bool:"):
				fmt.Fprintf(&b, "      vx_bool %s %s\n", strings.TrimPrefix(in.Flag, "bool:"), v)
			case in.Flag != "":
				fmt.Fprintf(&b, "      vx_flag %s %s\n", in.Flag, v)
			}
		}
		b.WriteString("      ;;\n")
	}
	b.WriteString(`    *)
      return 1
      ;;
  esac
}

# vx_flag NAME VALUE adds NAME VALUE when VALUE is not empty.
vx_flag() {
  if [ -n "$2" ]; then cmd+=("$1" "$2"); fi
}

# vx_bool NAME VALUE adds NAME when VALUE is true.
vx_bool() {
  if [ "$2" = "true" ]; then cmd+=("$1"); fi
}

# vx_flag_lines NAME VALUE adds NAME and each non-empty line, trimmed, once per line.
vx_flag_lines() {
  local line
  while IFS= read -r line; do
    line="${line#"${line%%[![:space:]]*}"}"
    line="${line%"${line##*[![:space:]]}"}"
    if [ -n "$line" ]; then cmd+=("$1" "$line"); fi
  done <<<"$2"
}

# vx_lines VALUE adds each non-empty line, trimmed, as one argument.
vx_lines() {
  local line
  while IFS= read -r line; do
    line="${line#"${line%%[![:space:]]*}"}"
    line="${line%"${line##*[![:space:]]}"}"
    if [ -n "$line" ]; then cmd+=("$line"); fi
  done <<<"$1"
}
`)
	return b.String()
}
